const addTableColumnsToReport = (tableHeader, yearsArray) => {
  // Find the table header row by its ID
  const tableHeaderRow = document.getElementById(tableHeader);

  console.dir(tableHeaderRow);

  // Get the reference to the "avg" <th> element
  const avgTh = tableHeaderRow.children[1];

  // Iterate through the selectedYearArray and add new columns
  yearsArray.forEach((year) => {
    // Create a new <th> element for each selected year
    const newTh = document.createElement('th');
    newTh.setAttribute('scope', 'col');
    newTh.setAttribute('class', 'px-6 py-3');
    newTh.innerText = year;

    // Insert the new <th> element before the "avg" <th>
    tableHeaderRow.insertBefore(newTh, avgTh);
  });
};

const findYearInObject = (year, object, innerData, dataKey) => {
  if (!object[dataKey]) {
    object[dataKey] = {};
  }
  if (!object[dataKey][year]) {
    object[dataKey][year] = [];
  }
  object[dataKey][year].push(innerData);
};

const processEnrollmentData = (years, data) => {
  years.forEach((year) => {
    const matchingData = data.filter(
      (item) => item.children.year.innerHTML === year.toString()
    );
    matchingData.forEach((item) => {
      const {
        students: studentsPeer,
        'students - percent change': percentChangePeer,
        'students - average enrollment': averageEnrollmentPeer,
        'students - peak enrollment': peakEnrollmentPeer,
        'student/faculty ratio': studentFacultyRatioPeer
      } = item.children;

      const year = item.children.year.innerHTML;

      findYearInObject(
        year,
        objectData,
        studentsPeer.innerHTML,
        'studentAverageEnrollment_Main'
      );
      findYearInObject(
        year,
        objectData,
        percentChangePeer.innerHTML,
        'studentAverageEnrollment_PercentChange_Main'
      );
    });

    const matchingClientData = clientData.filter(
      (item) => item.children.year.innerHTML === year.toString()
    );
    matchingClientData.forEach((item) => {
      const {
        students: studentsClient,
        'students - percent change': percentChangeClient,
        'students - average enrollment': averageEnrollmentClient,
        'students - peak enrollment': peakEnrollmentClient,
        'student/faculty ratio': studentFacultyRatioClient
      } = item.children;

      const year = item.children.year.innerHTML;

      findYearInObject(
        year,
        objectData,
        studentsClient.innerHTML,
        'studentAverageEnrollment_Client'
      );
      findYearInObject(
        year,
        objectData,
        percentChangeClient.innerHTML,
        'studentAverageEnrollment_PercentChange_Client'
      );
    });
  });

  localStorage.removeItem('enrollmentData');
  localStorage.setItem('enrollmentData', JSON.stringify(objectData));

  checkLastRenderedComponent();
};

